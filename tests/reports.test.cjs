const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const XLSX = require('xlsx');
const { emptyRegister } = require('../.test-build/model');
const { applyImport, parseWorkbook } = require('../.test-build/import');
const { prepareMonth } = require('../.test-build/billing');
const { recordBillCorrection } = require('../.test-build/bill-corrections');
const { reportExcelBytes, reportData, reportHtml } = require('../.test-build/report-format');
test('Excel preserves numeric dues, scoped totals and Malayalam; print escapes names', () => {
  const r = emptyRegister(); let serial = 0; const id = () => 'report-' + ++serial;
  applyImport(r, parseWorkbook(fs.readFileSync('verification/fixtures/temple-road.xlsx'), r, '2026-06', 'hash', 'fixture', id), '2026-06', id);
  r.households[0].versions[0].name = '<Anu & family>';
  prepareMonth(r, '2026-06', id); r.language = 'ml';
  const selection = { month: '2026-06', type: 'dues', scope: 'boy', scopeId: r.boys[0].id };
  const expected = reportData(r, selection);
  const book = XLSX.read(reportExcelBytes(r, selection), { type: 'array' });
  const rows = XLSX.utils.sheet_to_json(book.Sheets.NMS, { header: 1 });
  assert.equal(rows.length, expected.rows.length + 4);
  assert.equal(rows[0][0], 'മാസ കുടിശ്ശിക');
  assert.equal(typeof rows[3][6], 'number');
  assert.equal(rows.at(-1)[0], 'ആകെ');
  assert.equal(rows.at(-1)[6], expected.total.remaining / 100);
  assert.ok(expected.rows.length < r.households.length);
  const html = reportHtml(r, selection);
  assert.ok(html.includes('&lt;Anu &amp; family&gt;'));
  assert.ok(!html.includes('<Anu & family>'));
  assert.ok(html.includes('lang="ml"'));
});
test('dues exports show custom items and copy counts while master lists keep subscriptions for the month', () => {
  const r = emptyRegister();
  let serial = 0;
  const id = () => 'report-item-' + ++serial;
  applyImport(r, parseWorkbook(fs.readFileSync('verification/fixtures/temple-road.xlsx'), r, '2026-06', 'hash', 'fixture', id), '2026-06', id);
  const multiple = r.households[1];
  const multipleSubscription = multiple.versions[0].subscriptions[0];
  multipleSubscription.quantity = 2;
  const copyLabel = r.periodicals.find(paper => paper.id === multipleSubscription.periodicalId).code + ' × 2';
  prepareMonth(r, '2026-06', id);
  const selection = { month: '2026-06', type: 'dues', scope: 'all', scopeId: '' };
  const master = { ...selection, type: 'master' };
  const bill = r.bills.find(b => b.month === selection.month && b.lines.length);
  const starting = reportData(r, selection).rows.find(row => row.customerId === bill.customerId);
  const deliveryPapers = reportData(r, master).rows.find(row => row.customerId === bill.customerId).papers;
  const itemName = 'വിശേഷ <പതിപ്പ്>';
  recordBillCorrection(r, bill, { lines: bill.lines.slice(1),
    customItems: [{ id: id(), name: itemName, amount: 1234 }, { id: id(), name: 'Monthly charge', amount: 500, recurring: true }] },
    { id: id(), at: r.updatedAt, item: itemName });
  const current = reportData(r, selection).rows.find(row => row.customerId === bill.customerId);
  assert.equal(current.original, starting.original - bill.lines[0].quantity * bill.lines[0].rate + 1734);
  assert.ok(current.papers.includes(itemName + ' (₹12.34)'));
  assert.ok(current.papers.includes('Monthly charge (₹5)'));
  assert.equal(reportData(r, master).rows.find(row => row.customerId === bill.customerId).papers, deliveryPapers);
  assert.ok(!reportHtml(r, master).includes('വിശേഷ'));
  assert.ok(!reportHtml(r, master).includes('Monthly charge'));
  assert.ok(reportHtml(r, selection).includes('വിശേഷ &lt;പതിപ്പ്&gt; (₹12.34)'));
  const book = XLSX.read(reportExcelBytes(r, selection), { type: 'array' });
  const rows = XLSX.utils.sheet_to_json(book.Sheets.NMS, { header: 1 });
  assert.ok(rows.some(row => typeof row[3] === 'string' && row[3].includes(itemName) && typeof row[5] === 'number'));
  assert.ok(reportData(r, master).rows.find(row => row.customerId === multiple.id).papers.includes(copyLabel));
  assert.ok(rows.some(row => typeof row[3] === 'string' && row[3].includes(copyLabel)));
  assert.ok(reportData(r, master).rows.every(row => !row.papers.includes(' × 1')));
});
